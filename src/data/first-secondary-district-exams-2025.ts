function makeQuestion(input: DistrictQuestionInput) {
  const tags = [
    "First Secondary",
    "First Term",
    "District Exams 2025",
    input.administration,
    input.section,
    "MCQ",
  ];

  return {
    ...input,
    stage: "Secondary",
    grade: "First Secondary",
    curriculum: "Ministry",
    term: "First",
    source,
    publisher: "Ministry District Examination Collections",
    unit: "District Exams 2025",
    lesson: input.administration,
    topic: `${input.administration} · ${input.section}`,
    skill: input.domainCategory,
    difficulty: "Medium",
    points: 1,
    questionType: input.questionType || "mcq",
    correctAnswer: Array.isArray(input.correctAnswer)
      ? JSON.stringify(input.correctAnswer)
      : input.correctAnswer,
    tags,
  };
}

